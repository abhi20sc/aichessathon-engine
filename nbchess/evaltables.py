def _flip(t):
    """a8..h1 reading order -> a1..h8 square indexing."""
    out = np.zeros(64, dtype=np.int32)
    for i, v in enumerate(t):
        rank = 7 - i // 8
        out[rank * 8 + i % 8] = v
    return out


